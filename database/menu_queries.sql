-- 1. Categories
SELECT id, name, sort_order FROM categories ORDER BY sort_order, name;

-- 2. Products in a category (:category_id)
SELECT id, name, description, price, image_path, is_active
FROM menu_items WHERE category_id = :category_id ORDER BY name;

-- 3. Products currently available
SELECT m.*, c.name AS category_name FROM menu_items m
JOIN categories c ON c.id = m.category_id WHERE m.is_active = 1 ORDER BY c.sort_order, m.name;

-- 4. Name search (:keyword, e.g. '%kim chi%')
SELECT * FROM menu_items WHERE name LIKE :keyword ORDER BY name;

-- 5. Price range (:min_price, :max_price)
SELECT * FROM menu_items WHERE price BETWEEN :min_price AND :max_price ORDER BY price, name;

-- 6. Product details (:product_id)
SELECT m.*, c.name AS category_name FROM menu_items m
JOIN categories c ON c.id = m.category_id WHERE m.id = :product_id;

-- 7. Allowed toppings for a product (:product_id)
SELECT t.* FROM product_toppings pt JOIN toppings t ON t.id = pt.topping_id
WHERE pt.product_id = :product_id AND t.is_active = 1 ORDER BY t.name;

-- 8. Insert product (bind all named parameters)
INSERT INTO menu_items (category_id, name, description, price, image_path, is_active)
VALUES (:category_id, :name, :description, :price, :image_path, 1);

-- 9. Update price (:product_id, :price)
UPDATE menu_items SET price = :price WHERE id = :product_id;

-- 10. Set availability (:product_id, :is_active = 0 or 1)
UPDATE menu_items SET is_active = :is_active WHERE id = :product_id;

-- 11. Total for one product plus selected allowed toppings.
-- Bind :product_id and :quantity. Replace the sample IDs in IN (...) with
-- bound placeholders generated by the backend; an empty selection contributes 0.
SELECT (m.price + COALESCE(SUM(t.price), 0)) * :quantity AS total_amount
FROM menu_items m
LEFT JOIN product_toppings pt ON pt.product_id = m.id AND pt.topping_id IN (1, 2)
LEFT JOIN toppings t ON t.id = pt.topping_id AND t.is_active = 1
WHERE m.id = :product_id
GROUP BY m.id, m.price;
